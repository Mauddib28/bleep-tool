def dissect_advertisement(
    manufacturer_data: Optional[Dict[Any, Any]] = None,
    service_data: Optional[Dict[Any, Any]] = None,
    service_uuids: Optional[List[str]] = None,
    advertising_data: Optional[Dict[Any, Any]] = None,
) -> Dict[str, Any]:
    """Dissect advertisement fields into a structured, lossless result.

    All arguments are optional and tolerant of D-Bus wrapper types. The return
    value always contains ``manufacturer_data``, ``service_data``,
    ``service_uuids``, ``advertising_data`` lists and a ``summary`` dict.
    """
    result: Dict[str, Any] = {
        "manufacturer_data": [],
        "service_data": [],
        "service_uuids": [],
        "advertising_data": [],
        "summary": {"vendors": [], "protocols": []},
    }
    vendors: List[str] = []
    protocols: List[str] = []

    for cid_raw, val in (manufacturer_data or {}).items():
        try:
            cid = int(cid_raw)
        except (TypeError, ValueError):
            continue
        raw = _to_bytes(val)
        hints = _vendor_hints_company(cid, raw)
        entry: Dict[str, Any] = {
            "company_id": cid,
            "company_id_hex": f"0x{cid:04x}",
            "company": _resolve_company_name(cid),
            "vendor_hints": hints,
            "raw_hex": raw.hex(),
            "ascii": _ascii(raw),
        }
        decoded = None
        if cid == COMPANY_ID__APPLE:
            decoded = _decode_ibeacon(raw) or _decode_apple_continuity(raw)
        elif len(raw) >= 23 and raw[0] == 0x02 and raw[1] == 0x15:
            decoded = _decode_ibeacon(raw)
        elif cid in _IBEACON_COMPACT_CIDS:
            decoded = _decode_ibeacon_compact(raw)
        if decoded:
            entry["decoded"] = decoded
            protocols.append(decoded["protocol"])
        vendors.extend(hints)
        result["manufacturer_data"].append(entry)

    for uuid_raw, val in (service_data or {}).items():
        raw = _to_bytes(val)
        uuid = str(uuid_raw)
        u16 = _uuid16_of(uuid)
        vendor_hint = _vendor_hint_service("SERVICE_DATA_UUID16", u16) if u16 else None
        protocol_label = SERVICE_DATA_PROTOCOL_LABELS.get(u16) if u16 else None
        entry = {
            "uuid": uuid,
            "uuid_16": u16,
            "name": _sig_uuid_name(uuid),
            "protocol": protocol_label,
            "vendor_hints": [vendor_hint] if vendor_hint else [],
            "raw_hex": raw.hex(),
            "ascii": _ascii(raw),
        }
        if u16 == "feaa":
            decoded = _decode_eddystone(raw)
            if decoded:
                entry["decoded"] = decoded
                protocols.append("eddystone")
        if protocol_label:
            protocols.append(protocol_label)
        if vendor_hint:
            vendors.append(vendor_hint)
        result["service_data"].append(entry)

    feaa_payload_seen = any(
        (e.get("uuid_16") == "feaa" and e.get("decoded"))
        for e in result["service_data"]
    )

    for uuid_raw in (service_uuids or []):
        uuid = str(uuid_raw)
        u16 = _uuid16_of(uuid)
        u128 = uuid.strip().lower().replace("-", "")
        vendor_hint = (
            _vendor_hint_service("SERVICE_UUID16", u16) if u16 else None
        ) or _vendor_hint_service("SERVICE_UUID128", u128)
        entry = {"uuid": uuid, "uuid_16": u16, "name": _sig_uuid_name(uuid),
                 "vendor_hints": [vendor_hint] if vendor_hint else []}
        if u16 == "feaa" and not feaa_payload_seen:
            entry["decoded"] = {
                "protocol": "eddystone",
                "frame": "pending",
                "note": "uuid-advertised; payload not yet captured",
                "confidence": "low",
            }
            protocols.append("eddystone_pending")
        if vendor_hint:
            vendors.append(vendor_hint)
        result["service_uuids"].append(entry)

    for ad_raw, val in (advertising_data or {}).items():
        try:
            ad_type = int(ad_raw)
        except (TypeError, ValueError):
            continue
        raw = _to_bytes(val)
        result["advertising_data"].append({
            "ad_type": ad_type,
            "ad_type_hex": f"0x{ad_type:02x}",
            "name": _resolve_ad_type_name(ad_type),
            "raw_hex": raw.hex(),
            "ascii": _ascii(raw),
        })

    result["summary"]["vendors"] = sorted(set(vendors))
    result["summary"]["protocols"] = sorted(set(protocols))
    return result


def format_beacon_summary(dissection: Optional[Mapping[str, Any]]) -> str:
    """Return a compact one-line beacon identity tag for scan/survey output.

    Empty string when no beacon protocols were decoded. Examples::

        [ibeacon_compact m=1/i=169 tx=-59] [feaa-pending]
        [ibeacon m=1/i=2] [eddystone url=https://espressif.com]
    """
    if not dissection:
        return ""
    tags: List[str] = []
    for entry in dissection.get("manufacturer_data") or []:
        decoded = entry.get("decoded") or {}
        proto = decoded.get("protocol")
        if proto in ("ibeacon", "ibeacon_compact"):
            major = decoded.get("major")
            minor = decoded.get("minor")
            tx = decoded.get("tx_power")
            parts = [proto]
            if major is not None and minor is not None:
                parts.append(f"m={major}/i={minor}")
            if tx is not None:
                parts.append(f"tx={tx}")
            tags.append("[" + " ".join(parts) + "]")
    for entry in dissection.get("service_data") or []:
        decoded = entry.get("decoded") or {}
        if decoded.get("protocol") == "eddystone":
            frame = decoded.get("frame")
            if frame == "url" and decoded.get("url"):
                tags.append(f"[eddystone url={decoded['url']}]")
            elif frame:
                tags.append(f"[eddystone {frame}]")
            else:
                tags.append("[eddystone]")
    for entry in dissection.get("service_uuids") or []:
        decoded = entry.get("decoded") or {}
        if decoded.get("frame") == "pending":
            tags.append("[feaa-pending]")
    if not tags:
        protocols = (dissection.get("summary") or {}).get("protocols") or []
        if "eddystone_pending" in protocols:
            tags.append("[feaa-pending]")
        elif "eddystone" in protocols:
            tags.append("[eddystone]")
        elif "ibeacon_compact" in protocols:
            tags.append("[ibeacon_compact]")
        elif "ibeacon" in protocols:
            tags.append("[ibeacon]")
    # Preserve order while de-duplicating
    seen = set()
    ordered: List[str] = []
    for tag in tags:
        if tag not in seen:
            seen.add(tag)
            ordered.append(tag)
    return " ".join(ordered)


# ---------------------------------------------------------------------------
# Persisted-record adapter (shared by CLI ``db show`` and AoI reports)
# ---------------------------------------------------------------------------

def _record_field(record: Mapping[str, Any], key: str) -> Any:
    """Fetch an advertisement field from a flat record or its nested ``device`` row.

    ``get_device_detail()`` nests the ``devices``-table row under ``device`` while
    AoI enrichment dicts carry the same fields at the top level — check both so a
    single caller works for either shape.
    """
    if key in record and record[key] is not None:
        return record[key]
    dev = record.get("device")
    if isinstance(dev, Mapping):
        return dev.get(key)
    return None


def _hex_map_to_bytes(raw: Any) -> Dict[Any, bytes]:
    """Coerce a persisted ``{key: hex-str | byte-list}`` map (or its JSON string
    form) into ``{key: bytes}``. Unparseable entries are skipped, not raised."""
    if isinstance(raw, str):
        try:
            raw = _json.loads(raw)
        except (ValueError, TypeError):
            return {}
    out: Dict[Any, bytes] = {}
    if isinstance(raw, Mapping):
        for k, v in raw.items():
            try:
                out[k] = bytes.fromhex(v) if isinstance(v, str) else _to_bytes(v)
            except (ValueError, TypeError):
                continue
    return out


def dissect_persisted_record(record: Mapping[str, Any]) -> Optional[Dict[str, Any]]:
    """Reconstruct dissector inputs from a persisted device/adv record and dissect.

    Accepts the flat advertisement fields as stored in the ``devices`` table (or
    an AoI enrichment dict): ``manufacturer_id`` + ``manufacturer_data``,
    ``service_data``, ``advertising_data`` and ``uuids``. Values may be ``bytes``
    (SQLite BLOB), hex strings, D-Bus byte lists, or JSON strings — all are
    tolerated. Fields are looked up top-level first, then under a nested
    ``device`` row.

    Returns the :func:`dissect_advertisement` result dict, or ``None`` when the
    record carries no advertisement data. Never raises — enrichment must not
    break its callers.
    """
    try:
        service_data = _hex_map_to_bytes(_record_field(record, "service_data"))
        advertising_data = {
            int(k): v
            for k, v in _hex_map_to_bytes(_record_field(record, "advertising_data")).items()
            if str(k).lstrip("-").isdigit()
        }

        manufacturer_data: Dict[int, bytes] = {}
        mfr_id = _record_field(record, "manufacturer_id")
        mfr_val = _record_field(record, "manufacturer_data")
        if mfr_id is not None and mfr_val is not None:
            try:
                mv = bytes.fromhex(mfr_val) if isinstance(mfr_val, str) else _to_bytes(mfr_val)
                manufacturer_data[int(mfr_id)] = mv
            except (ValueError, TypeError):
                pass

        uuids = _record_field(record, "uuids")
        if isinstance(uuids, str):
            try:
                uuids = _json.loads(uuids)
            except (ValueError, TypeError):
                uuids = []
        if not isinstance(uuids, list):
            uuids = []

        if not (manufacturer_data or service_data or advertising_data or uuids):
            return None

        return dissect_advertisement(
            manufacturer_data=manufacturer_data or None,
            service_data=service_data or None,
            service_uuids=uuids or None,
            advertising_data=advertising_data or None,
        )
    except Exception:  # noqa: BLE001 - enrichment must never break the caller
        return None
