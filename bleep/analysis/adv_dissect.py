"""Advertisement dissection (G-7.5).

Parse BlueZ-exposed advertisement blobs — ``ManufacturerData``,
``ServiceData``, advertised service UUIDs, and ``AdvertisingData`` — into
structured, attributed fields.

Design goals:
    * **Lossless** — every entry keeps its raw hex *and* a printable-ASCII
      rendering. Advertisements sometimes carry clear text (e.g. some
      Bluetooth headsets embed a model/name), so no captured byte is dropped.
    * **Two-source attribution** — Bluetooth SIG assigned numbers
      (``bt_ref.uuids`` via the shared resolvers) *plus* vendor/community
      fingerprints (``bt_ref.vendor_adv_specs``, generated by
      ``update_vendor_specs``).
    * **Graceful** — a protocol decoder failure never discards the raw entry.

The dissector is pure and side-effect free; callers decide whether to persist
or render the result.  See ``docs/adv_dissection.md``.
"""
from __future__ import annotations

import json as _json
from typing import Any, Dict, List, Mapping, Optional

from bleep.bt_ref.constants import (
    BT_SIG_BASE_UUID_SUFFIX,
    COMPANY_ID__APPLE,
    SERVICE_DATA_PROTOCOL_LABELS,
)
from bleep.ble_ops.common.conversion import _resolve_ad_type_name, _resolve_company_name

# Curated service-data/beacon labels are centralised in ``bt_ref.constants`` (the
# canonical UUID reference layer) and re-exported here for callers/tests. The
# classifier imports the same source, so the two cannot drift. See
# docs/adv_dissection.md ("Known UUID attribution corrections").
__all__ = [
    "SERVICE_DATA_PROTOCOL_LABELS",
    "dissect_advertisement",
    "dissect_persisted_record",
    "format_beacon_summary",
]

_SIG_SUFFIX = BT_SIG_BASE_UUID_SUFFIX.lower()

# Apple Continuity TLV message types (device-library apple_dispatcher).
_APPLE_CONTINUITY_TYPES: Dict[int, str] = {
    0x02: "ibeacon",
    0x05: "airdrop",
    0x06: "homekit",
    0x07: "proximity_pairing",
    0x08: "hey_siri",
    0x09: "airplay_target",
    0x0A: "airplay_source",
    0x0B: "magic_switch",
    0x0C: "handoff",
    0x0D: "tethering_target",
    0x0E: "tethering_source",
    0x0F: "nearby_action",
    0x10: "nearby_info",
    0x12: "find_my",
}

# Eddystone URL scheme prefixes and expansion codes (device-library eddystone).
_EDDYSTONE_SCHEMES = ["http://www.", "https://www.", "http://", "https://"]
_EDDYSTONE_EXPANSIONS = [
    ".com/", ".org/", ".edu/", ".net/", ".info/", ".biz/", ".gov/",
    ".com", ".org", ".edu", ".net", ".info", ".biz", ".gov",
]


def _to_bytes(value: Any) -> bytes:
    """Best-effort coerce a D-Bus byte array / list / bytes to ``bytes``."""
    if value is None:
        return b""
    if isinstance(value, (bytes, bytearray)):
        return bytes(value)
    try:
        return bytes(int(b) & 0xFF for b in value)
    except (TypeError, ValueError):
        return b""


def _ascii(raw: bytes) -> str:
    """Printable-ASCII rendering; non-printable bytes → U+FFFD (lossless pair)."""
    return "".join(chr(b) if 0x20 <= b <= 0x7E else "\ufffd" for b in raw)


def _uuid16_of(uuid: str) -> Optional[str]:
    """Return the 16-bit form (lower-case, 4 hex) of a UUID string, if derivable."""
    s = str(uuid).strip().lower()
    if len(s) == 4:
        return s
    # 128-bit BT SIG base UUID: 0000XXXX + BT_SIG_BASE_UUID_SUFFIX
    if len(s) >= 8 and s[8:] == _SIG_SUFFIX:
        return s[4:8]
    return None


def _vendor_specs():
    try:
        from bleep.bt_ref import vendor_adv_specs as _specs
        return _specs
    except Exception:  # noqa: BLE001 - reference module always committed, be safe
        return None


def _sig_uuid_name(uuid: str) -> Optional[str]:
    try:
        from bleep.bt_ref.utils import get_name_from_uuid
        name = get_name_from_uuid(uuid)
        return name if name and name != "Unknown" else None
    except Exception:  # noqa: BLE001
        return None


# ---------------------------------------------------------------------------
# Protocol decoders
# ---------------------------------------------------------------------------

def _decode_ibeacon(payload: bytes) -> Optional[Dict[str, Any]]:
    """Decode an iBeacon payload (0x02 0x15 <uuid16> <major> <minor> <tx>)."""
    if len(payload) < 23 or payload[0] != 0x02 or payload[1] != 0x15:
        return None
    return {
        "protocol": "ibeacon",
        "uuid": payload[2:18].hex(),
        "major": int.from_bytes(payload[18:20], "big"),
        "minor": int.from_bytes(payload[20:22], "big"),
        "tx_power": int.from_bytes(payload[22:23], "big", signed=True),
    }


# Compact Espressif-observed framing: CID 0xFFFF + exactly 5 bytes.
_IBEACON_COMPACT_CIDS = frozenset({0xFFFF})


def _decode_ibeacon_compact(payload: bytes) -> Optional[Dict[str, Any]]:
    """Decode allowlisted compact major/minor/tx manufacturer payloads."""
    if len(payload) != 5:
        return None
    return {
        "protocol": "ibeacon_compact",
        "uuid": None,
        "major": int.from_bytes(payload[0:2], "big"),
        "minor": int.from_bytes(payload[2:4], "big"),
        "tx_power": int.from_bytes(payload[4:5], "big", signed=True),
    }


def _decode_apple_continuity(payload: bytes) -> Optional[Dict[str, Any]]:
    """Split Apple Continuity manufacturer payload into TLV messages."""
    messages: List[Dict[str, Any]] = []
    i = 0
    while i + 1 < len(payload):
        msg_type = payload[i]
        length = payload[i + 1]
        data = payload[i + 2 : i + 2 + length]
        entry = {
            "type": f"0x{msg_type:02x}",
            "name": _APPLE_CONTINUITY_TYPES.get(msg_type, "unknown"),
            "raw_hex": data.hex(),
        }
        if msg_type == 0x02:
            ibeacon = _decode_ibeacon(bytes([0x02, len(data)]) + data)
            if ibeacon:
                entry["decoded"] = ibeacon
        messages.append(entry)
        i += 2 + length
    return {"protocol": "apple_continuity", "messages": messages} if messages else None


def _decode_eddystone(payload: bytes) -> Optional[Dict[str, Any]]:
    """Decode an Eddystone service-data frame (UID / URL / TLM / EID)."""
    if not payload:
        return None
    frame = payload[0]
    if frame == 0x00 and len(payload) >= 18:
        return {"protocol": "eddystone", "frame": "uid",
                "namespace": payload[2:12].hex(), "instance": payload[12:18].hex()}
    if frame == 0x10 and len(payload) >= 3:
        scheme = _EDDYSTONE_SCHEMES[payload[2]] if payload[2] < len(_EDDYSTONE_SCHEMES) else ""
        url = scheme
        for b in payload[3:]:
            url += _EDDYSTONE_EXPANSIONS[b] if b < len(_EDDYSTONE_EXPANSIONS) else chr(b) if 0x20 <= b <= 0x7E else ""
        return {"protocol": "eddystone", "frame": "url", "url": url}
    if frame == 0x20 and len(payload) >= 14:
        return {"protocol": "eddystone", "frame": "tlm",
                "battery_mv": int.from_bytes(payload[2:4], "big"),
                "temperature_raw": payload[4:6].hex(),
                "adv_count": int.from_bytes(payload[6:10], "big"),
                "uptime_100ms": int.from_bytes(payload[10:14], "big")}
    if frame == 0x30 and len(payload) >= 10:
        return {"protocol": "eddystone", "frame": "eid", "eid": payload[2:10].hex()}
    return {"protocol": "eddystone", "frame": f"0x{frame:02x}"}


# ---------------------------------------------------------------------------
# Attribution helpers
# ---------------------------------------------------------------------------

def _vendor_hints_company(cid: int, payload: bytes) -> List[str]:
    specs = _vendor_specs()
    if specs is None:
        return []
    key = f"{cid:04x}"
    hints = list(getattr(specs, "COMPANY_ID", {}).get(key, []))
    ph = payload.hex()
    for entry in getattr(specs, "MANUFACTURER_PREFIX", []):
        if entry.get("company_id") == key and ph.startswith(entry.get("prefix", "")):
            if entry["name"] not in hints:
                hints.append(entry["name"])
    return hints


def _vendor_hint_service(table_name: str, key: str) -> Optional[str]:
    specs = _vendor_specs()
    if specs is None:
        return None
    return getattr(specs, table_name, {}).get(key)


